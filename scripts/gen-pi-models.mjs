#!/usr/bin/env node
/**
 * Generates `apps/desktop/src/piModels.ts` from the Pi SDK's provider catalog
 * (`@earendil-works/pi-ai` inside apps/pi-runtime), so the desktop settings
 * page can offer real dropdowns instead of free-text model inputs.
 *
 * Usage: node scripts/gen-pi-models.mjs   (run from the repo root, after pnpm install)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "apps", "pi-runtime", "node_modules", "@earendil-works", "pi-ai", "dist", "providers", "data");
const outFile = join(root, "apps", "desktop", "src", "piModels.ts");

// Providers the pi-runtime sidecar resolves API keys for (agent.ts ENV_API_KEYS).
const PROVIDERS = [
  { id: "anthropic", label: "Anthropic", envVar: "ANTHROPIC_API_KEY" },
  { id: "openai", label: "OpenAI", envVar: "OPENAI_API_KEY" },
  { id: "google", label: "Google", envVar: "GOOGLE_API_KEY" },
  { id: "deepseek", label: "DeepSeek", envVar: "DEEPSEEK_API_KEY" },
  { id: "openrouter", label: "OpenRouter", envVar: "OPENROUTER_API_KEY" },
  { id: "mistral", label: "Mistral", envVar: "MISTRAL_API_KEY" },
  { id: "groq", label: "Groq", envVar: "GROQ_API_KEY" },
  { id: "xai", label: "xAI", envVar: "XAI_API_KEY" },
];

// OpenRouter aggregates hundreds of slugs; only surface flagship models and
// let users type anything else via the custom-input fallback.
const OPENROUTER_CURATED = [
  "anthropic/claude-opus-5",
  "anthropic/claude-sonnet-5",
  "anthropic/claude-haiku-4.5",
  "openai/gpt-5.5",
  "openai/gpt-5.5-pro",
  "openai/gpt-5.2",
  "google/gemini-3.7-flash",
  "google/gemini-3.1-pro-preview",
  "deepseek/deepseek-v4-pro",
  "deepseek/deepseek-chat",
  "x-ai/grok-4.6",
  "moonshotai/kimi-k3",
  "qwen/qwen3.8-max",
  "mistralai/mistral-large-2512",
  "meta-llama/llama-4-maverick",
];

function loadModels(providerId) {
  const catalog = JSON.parse(readFileSync(join(dataDir, `${providerId}.json`), "utf8"));
  const byId = new Map();
  for (const group of Object.values(catalog)) {
    for (const model of Object.values(group)) {
      if (model?.id) {
        byId.set(model.id, {
          id: model.id,
          name: model.name ?? model.id,
          contextWindow: typeof model.contextWindow === "number" ? model.contextWindow : undefined,
          reasoning: model.reasoning === true,
        });
      }
    }
  }
  return [...byId.values()].sort((a, b) => a.id.localeCompare(b.id));
}

const providers = PROVIDERS.map(({ id, label, envVar }) => {
  let models = loadModels(id);
  if (id === "openrouter") {
    const curated = OPENROUTER_CURATED.flatMap((modelId) => models.filter((m) => m.id === modelId));
    const missing = OPENROUTER_CURATED.filter((modelId) => !curated.some((m) => m.id === modelId));
    if (missing.length > 0) {
      console.warn(`[gen-pi-models] curated OpenRouter models no longer in catalog: ${missing.join(", ")}`);
    }
    models = curated;
  }
  return { id, label, envVar, models };
});

const header = `// GENERATED by scripts/gen-pi-models.mjs — do not edit by hand.
// Source: @earendil-works/pi-ai provider catalog (${PROVIDERS.length} providers supported by the pi sidecar).
`;

const body = providers
  .map((p) => {
    const models = p.models
      .map((m) => `  { id: ${JSON.stringify(m.id)}, name: ${JSON.stringify(m.name)}, contextWindow: ${m.contextWindow ?? "undefined"}, reasoning: ${m.reasoning} },`)
      .join("\n");
    return `export const ${p.id.replace(/[^a-z]/g, "")}Models: PiModelOption[] = [\n${models}\n];`;
  })
  .join("\n\n");

const selects = providers.map((p) => `  { value: ${JSON.stringify(p.id)}, label: ${JSON.stringify(p.label)}, envVar: ${JSON.stringify(p.envVar)}, models: ${p.id.replace(/[^a-z]/g, "")}Models },`).join("\n");

const file = `${header}

export interface PiModelOption {
  id: string;
  name: string;
  contextWindow?: number;
  reasoning: boolean;
}

export interface PiProviderOption {
  value: string;
  label: string;
  envVar: string;
  models: PiModelOption[];
}

${body}

export const PI_PROVIDERS: PiProviderOption[] = [
${selects}
];
`;

writeFileSync(outFile, file);
console.log(`[gen-pi-models] wrote ${outFile} (${providers.reduce((n, p) => n + p.models.length, 0)} models across ${providers.length} providers)`);
